inline int32_t fixed_sin(int16_t degrees) {
    while (degrees < 0) degrees += 360;
    degrees = degrees % 360;
    return sin_lut[degrees];
}

inline int32_t fixed_cos(int16_t degrees) {
    return fixed_sin(degrees + 90); // cos(x) = sin(x + 90)
}
